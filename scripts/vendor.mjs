// Builds what the plugin ships instead of node_modules. Paseo compiles the plugin from source with
// esbuild and supplies only its SDK, React, React Native, React Query, and zod; anything else must
// ship inside client/ or server/.
//
//   client/vendor/markdown-tokens.js        vendor-src/markdown-tokens.ts with micromark and its GFM
//                                           extensions; its declarations are the hand-written
//                                           markdown-tokens.d.ts beside it
//   client/vendor/THIRD_PARTY_LICENSES.txt
//
// Run after changing vendor-src/ or the pinned versions: npm run vendor
import { build } from "esbuild";
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const clientVendor = path.join(root, "client", "vendor");
const GENERATED = "// Generated by scripts/vendor.mjs; do not edit.\n";
const RULE = `\n\n${"-".repeat(72)}\n\n`;

/** The package directory and name that own a bundled file */
function owningPackage(file) {
  const parts = path.resolve(root, file).split(path.sep);
  const index = parts.lastIndexOf("node_modules");
  if (index === -1) return null;
  const size = parts[index + 1].startsWith("@") ? 2 : 1;
  return {
    name: parts.slice(index + 1, index + 1 + size).join("/"),
    directory: parts.slice(0, index + 1 + size).join(path.sep),
  };
}

function licenseText(directory) {
  const file = readdirSync(directory).find((name) => /^(licen[cs]e|copying|unlicense)([.-]|$)/i.test(name));
  if (!file) throw new Error(`No license file in ${directory}`);
  return readFileSync(path.join(directory, file), "utf8").trim();
}

function packageVersion(directory) {
  return JSON.parse(readFileSync(path.join(directory, "package.json"), "utf8")).version;
}

mkdirSync(clientVendor, { recursive: true });
const result = await build({
  entryPoints: [path.join(root, "vendor-src", "markdown-tokens.ts")],
  bundle: true,
  // ES module syntax lets the Node test runner load the bundle from this typeless package
  format: "esm",
  // The neutral platform matches no "browser" export condition, so decode-named-character-reference
  // brings its entity table rather than a DOM decoder the tests could not run
  platform: "neutral",
  mainFields: ["module", "main"],
  target: "es2020",
  minify: true,
  legalComments: "none",
  metafile: true,
  outfile: path.join(clientVendor, "markdown-tokens.js"),
  banner: { js: GENERATED },
});

const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  const owner = owningPackage(input);
  if (owner) packages.set(owner.name, owner.directory);
}
const notices = [...packages]
  .sort(([left], [right]) => left.localeCompare(right))
  .map(([name, directory]) => `${name}@${packageVersion(directory)}\n\n${licenseText(directory)}`);
writeFileSync(
  path.join(clientVendor, "THIRD_PARTY_LICENSES.txt"),
  `Third-party code in client/vendor/markdown-tokens.js\n\n${notices.join(RULE)}\n`,
);

const bytes = statSync(path.join(clientVendor, "markdown-tokens.js")).size;
console.log(`markdown-tokens.js: ${(bytes / 1024).toFixed(0)} KB from ${packages.size} packages`);
